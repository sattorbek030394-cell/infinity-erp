const esc = (s: string) =>
  s.replace(/[&<>"]/g, (c) =>
    c === "&" ? "&amp;" : c === "<" ? "&lt;" : c === ">" ? "&gt;" : "&quot;",
  );

const som = (n: number) => n.toLocaleString("ru-RU").replace(/\u00a0/g, " ");

const kun = (d: Date) =>
  String(d.getDate()).padStart(2, "0") +
  "." +
  String(d.getMonth() + 1).padStart(2, "0") +
  "." +
  d.getFullYear();

